const sqlite3 = require('sqlite3').verbose();
const path = require('path');
const fs = require('fs');

const DB_DIR = path.join(__dirname, '..', 'data');
const DB_PATH = path.join(DB_DIR, 'stocks.db');

if (!fs.existsSync(DB_DIR)) {
  fs.mkdirSync(DB_DIR, { recursive: true });
}

const db = new sqlite3.Database(DB_PATH, (err) => {
  if (err) {
    console.error('❌ SQLite 연결 실패:', err.message);
  } else {
    console.log('✅ SQLite 데이터베이스 연결 성공:', DB_PATH);
    initTablesAndSeed();
  }
});

function initTablesAndSeed() {
  db.serialize(() => {
    // 1. Stocks
    db.run(`
      CREATE TABLE IF NOT EXISTS stocks (
        symbol TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        market TEXT NOT NULL,
        assetType TEXT DEFAULT 'STOCK',
        sector TEXT,
        price REAL,
        changeRate REAL,
        volume INTEGER,
        marketCap REAL,
        per REAL,
        pbr REAL,
        psr REAL,
        roe REAL,
        dividendYield REAL,
        debtRatio REAL,
        currentRatio REAL,
        interestCoverage REAL,
        rsi14 REAL,
        high52w REAL,
        low52w REAL,
        currency TEXT DEFAULT 'KRW',
        warningBadges TEXT,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      )
    `);

    // 2. Market Indices
    db.run(`
      CREATE TABLE IF NOT EXISTS market_indices (
        code TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        value REAL NOT NULL,
        change REAL,
        changeRate REAL,
        sparkline TEXT,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      )
    `);

    // 3. Financials (DART 분기/연간 실적)
    db.run(`
      CREATE TABLE IF NOT EXISTS financials (
        symbol TEXT NOT NULL,
        fiscal_year INTEGER NOT NULL,
        quarter TEXT NOT NULL,
        revenue REAL,
        operating_income REAL,
        net_income REAL,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (symbol, fiscal_year, quarter)
      )
    `);

    // 3. Sectors
    db.run(`
      CREATE TABLE IF NOT EXISTS sectors (
        name TEXT PRIMARY KEY,
        changeRate REAL,
        marketCap REAL,
        topStock TEXT
      )
    `);

    // 4. News
    db.run(`
      CREATE TABLE IF NOT EXISTS news (
        id TEXT PRIMARY KEY,
        symbol TEXT,
        companyName TEXT,
        title TEXT NOT NULL,
        summary TEXT,
        source TEXT,
        date TEXT,
        url TEXT,
        sentiment TEXT,
        isDisclosure INTEGER DEFAULT 0
      )
    `);

    // 5. Watchlist
    db.run(`
      CREATE TABLE IF NOT EXISTS watchlist (
        symbol TEXT PRIMARY KEY,
        name TEXT,
        added_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      )
    `);

    // 6. Market Rankings Cache (카테고리별/시장별 실시간 순위 캐시)
    db.run(`
      CREATE TABLE IF NOT EXISTS market_rankings (
        category TEXT NOT NULL,
        market TEXT NOT NULL,
        ranking INTEGER NOT NULL,
        symbol TEXT NOT NULL,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (category, market, ranking)
      )
    `);

    // 데이터 존재 여부 확인 후 초기 시드 삽입
    db.get('SELECT COUNT(*) as count FROM stocks', (err, row) => {
      if (!err && row.count === 0) {
        seedInitialData();
      }
    });
  });
}

