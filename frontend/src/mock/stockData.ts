export function generateMockCandles(basePrice: number, days = 90): CandleData[] {
  const candles: CandleData[] = [];
  let currentClose = basePrice * 0.85;
  const now = new Date();

  for (let i = days; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const time = d.toISOString().split('T')[0];

    const changePercent = (Math.random() - 0.48) * 0.035;
    const open = currentClose;
    const close = Math.round(open * (1 + changePercent) * 100) / 100;
    const high = Math.round(Math.max(open, close) * (1 + Math.random() * 0.015) * 100) / 100;
    const low = Math.round(Math.min(open, close) * (1 - Math.random() * 0.015) * 100) / 100;
    const volume = Math.floor(Math.random() * 1000000) + 100000;

    candles.push({ time, open, high, low, close, volume });
    currentClose = close;
  }

  return candles;
}
